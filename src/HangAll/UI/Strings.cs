    public static bool IsEastAsian => Language is "zh" or "zh-Hant" or "ja" or "ko";

    public static void Refresh()
    {
        var was = Language;
        Language = Resolve();
        if (was != Language) LanguageChanged?.Invoke();
    }

    private static string Resolve()
    {
        var chosen = Core.Settings.Current.Language;
        if (chosen is "en" or "zh" or "zh-Hant" or "ja" or "ko") return chosen;
        var culture = CultureInfo.CurrentUICulture;
        var name = culture.Name;
        if (culture.TwoLetterISOLanguageName == "zh")
        {
            // Regional Traditional Chinese cultures share the region-neutral UI state.
            return name.Contains("Hant", StringComparison.OrdinalIgnoreCase) ||
                   name.StartsWith("zh-TW", StringComparison.OrdinalIgnoreCase) ||
                   name.StartsWith("zh-HK", StringComparison.OrdinalIgnoreCase) ||
                   name.StartsWith("zh-MO", StringComparison.OrdinalIgnoreCase)
                ? "zh-Hant"
                : "zh";
        }
        return culture.TwoLetterISOLanguageName switch
        {
            "ja" => "ja",
            "ko" => "ko",
            _ => "en",
        };
    }

    private static string L(string en, string? english = null) => Language switch
    {
        "zh" when Zh.TryGetValue(en, out var zh) => zh,
        "zh-Hant" when ZhHant.TryGetValue(en, out var zhHant) => zhHant,
        "ja" when Ja.TryGetValue(en, out var ja) => ja,
        "ko" when Ko.TryGetValue(en, out var ko) => ko,
        _ => english ?? en,
    };

